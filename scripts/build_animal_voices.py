#!/usr/bin/env python3
"""Build the offline voice bank from cached, licensed sources with ffmpeg.

Source pages/download URLs and hashes are preserved in the shipped manifest.
Put original files in .tools/animal-audio-sources first (see README).
No network requests are made by this script.
"""
import array
import argparse
import hashlib
import json
import math
from pathlib import Path
import subprocess
import wave

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / '.tools/animal-audio-sources'
OUT = ROOT / 'companion_flutter/assets/audio/animal_voices'
SOURCES = {
    'monkey': ('Monkey Sounds', 'AntumDeluge', 'CC0-1.0',
               'https://opengameart.org/content/monkey-sounds',
               [f'monkey-cc0/monkey-{i}.wav' for i in range(1, 4)],
               ['https://opengameart.org/sites/default/files/monkey-sounds_0.zip']),
    'cat': ('Cat SFX', 'SFX by Dan Knoflicek', 'CC-BY-3.0',
            'https://opengameart.org/content/cat-sfx', [f'cat{i}.wav' for i in range(1, 4)],
            [f'https://opengameart.org/sites/default/files/Cat%20{i}.wav' for i in range(1, 4)]),
    'dog': ('Dog sounds', 'pauliuw', 'CC0-1.0',
            'https://opengameart.org/content/dog-sounds',
            [f'dog/Dog/Dog Bark {i}.wav' for i in range(1, 4)],
            ['https://opengameart.org/sites/default/files/dog.7z']),
    'bunny': ('Rabbit Eating', 'Voltiment555', 'CC0-1.0',
              'https://opengameart.org/content/rabbit-eating', ['rabbit.wav'],
              ['https://opengameart.org/sites/default/files/RabbitEating.wav']),
    'penguin': ('Penguin SFX', 'Wolfgang Wozniak', 'CC-BY-3.0',
                'https://opengameart.org/content/penguin-sfx',
                [f'penguin/Penguin/penguin_call_ 0{i}.wav' for i in range(1, 4)],
                ['https://opengameart.org/sites/default/files/Penguin_sfx.zip']),
}
for animal, sound in [('fox', 'fox-09'), ('panda', 'panda-09'),
                      ('bear', 'bear-growl-01'), ('frog', 'animal-frog-02'),
                      ('owl', 'animal-owl-02')]:
    SOURCES[animal] = ('Stylized ' + animal + ' sound', 'SFXMint', 'CC0-1.0',
                       'https://sfxmint.com/sounds/' + sound, [animal + '.mp3'],
                       ['https://sfxmint.com/dl/' + sound + '.mp3'])
SOURCES['turtle'] = ('Original cartoon turtle chirps', 'RemindMe project', 'CC0-1.0',
                     'Generated by scripts/build_animal_voices.py', ['turtle.wav'], [])


def run(args):
    subprocess.run(args, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--animal', choices=SOURCES, help='Rebuild only this animal; retain existing assets/credits')
    args = parser.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    RAW.mkdir(parents=True, exist_ok=True)
    # Turtles use original character sounds, not a claimed wildlife recording.
    samples = array.array('h')
    for i in range(22050):
        t = i / 22050
        envelope = math.sin(math.pi * min(t / .7, 1)) ** 2 if t < .7 else 0
        frequency = 380 + 170 * math.sin(t * math.pi / .7)
        value = math.sin(2 * math.pi * frequency * t) + .18 * math.sin(4 * math.pi * frequency * t)
        samples.append(int(7000 * envelope * value))
    with wave.open(str(RAW / 'turtle.wav'), 'wb') as output:
        output.setparams((1, 2, 22050, 0, 'NONE', 'not compressed'))
        output.writeframes(samples.tobytes())
    manifest = {'schema': 1, 'description': f'{len(SOURCES) * 3} stylized voice sets, 3 variations per set. '
                'Pitch/timing edits are not separate recordings of individual animals.',
                'licenses': {'CC0-1.0': 'https://creativecommons.org/publicdomain/zero/1.0/',
                             'CC-BY-3.0': 'https://creativecommons.org/licenses/by/3.0/'},
                'sources': {}, 'clips': []}
    if args.animal:
        previous = json.loads((OUT / 'manifest.json').read_text())
        manifest['sources'] = previous['sources']
        manifest['clips'] = [clip for clip in previous['clips'] if clip['animal'] != args.animal]
    for animal, (title, credit, license_id, page, names, downloads) in SOURCES.items():
        if args.animal and animal != args.animal:
            continue
        paths = [RAW / name for name in names]
        for path in paths:
            if not path.exists():
                raise FileNotFoundError(f'Cache the licensed source first: {path}')
        manifest['sources'][animal] = dict(title=title, attribution=credit, license=license_id,
            page=page, downloads=downloads, files=[dict(name=n, sha256=sha(p)) for n, p in zip(names, paths)],
            note='Rabbit eating/rustles, not vocalizations' if animal == 'bunny' else
                 'Original synthesized character sounds, not real turtle calls' if animal == 'turtle' else
                 'AI-generated stylized animal sound' if credit == 'SFXMint' else
                 'Performed monkey imitations by AntumDeluge' if animal == 'monkey' else 'Recorded sound effects')
        for preset, pitch, tempo in [('soft', 1.10, .92), ('bright', 1.28, 1.08), ('deep', .82, .94)]:
            for variant in range(1, 4):
                source = paths[(variant - 1) % len(paths)]
                base = RAW / f'prepared-{animal}-{variant}.wav'
                offset = (variant - 1) * 2 if animal == 'bunny' else 0
                filters = ('highpass=f=90,lowpass=f=8000,'
                    'silenceremove=start_periods=1:start_duration=0.02:start_threshold=-40dB,'
                    'atrim=duration=2.2,asetpts=PTS-STARTPTS,aresample=22050')
                run(['ffmpeg', '-v', 'error', '-y', '-ss', str(offset), '-i', str(source),
                     '-af', filters, '-ac', '1', '-ar', '22050', str(base)])
                # Single-source species get three different rhythmic phrases.
                repeat = 1 if len(paths) > 1 or animal == 'bunny' else variant
                edit = f'asetrate={22050 * pitch},aresample=22050,atempo={tempo / pitch}'
                if repeat > 1:
                    edit += ',apad=pad_dur=0.16'
                    # A small PCM file makes finite loops deterministic.
                    padded = RAW / f'padded-{animal}-{preset}-{variant}.wav'
                    run(['ffmpeg', '-v', 'error', '-y', '-i', str(base), '-af', edit, str(padded)])
                    input_args = ['-stream_loop', str(repeat - 1), '-i', str(padded)]
                    edit = 'anull'
                else:
                    input_args = ['-i', str(base)]
                edit += ',atrim=duration=5,loudnorm=I=-23:TP=-4:LRA=7,afade=t=in:d=0.015,areverse,afade=t=in:d=0.04,areverse'
                name = f'{animal}_{preset}_{variant}.mp3'
                run(['ffmpeg', '-v', 'error', '-y', *input_args, '-af', edit,
                     '-ac', '1', '-ar', '22050', '-b:a', '64k', '-map_metadata', '-1', str(OUT / name)])
                manifest['clips'].append(dict(file=name, animal=animal, preset=preset,
                    variant=variant, source=source.relative_to(RAW).as_posix(),
                    pitch=pitch, tempo=tempo, repeats=repeat, offset=offset,
                    changes='Trimmed, filtered, pitch/time edited, normalized, faded; rhythmic repeats where noted',
                    sha256=sha(OUT / name)))
    (OUT / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    credits = ['COMPANION SOUND CREDITS', '',
        'Modified sounds: trimmed, filtered, pitch/time edited, normalized, faded and sometimes repeated.',
        'These are three sound-designed styles per animal, not three separately recorded individuals.', '']
    for animal, source in manifest['sources'].items():
        credits += [f"{animal.title()}: {source['title']} — {source['attribution']}",
                    source['page'], source['license'] + ' — ' + manifest['licenses'][source['license']],
                    source['note'], '']
    (OUT / 'CREDITS.txt').write_text('\n'.join(credits))
    print(f'Built {len(manifest["clips"])} clips ({sum(p.stat().st_size for p in OUT.glob("*.mp3")) / 1024:.0f} KiB)')


if __name__ == '__main__':
    main()
